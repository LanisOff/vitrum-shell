import { load, eq } from "./lib.mjs";
const w = load("welcome.js");
const s = w.steps();
eq(s.length, 7, "seven steps");
eq(s.map(x => x.id).join(","), "bar,dock,search,centre,widgets,settings,keys", "order");
eq(s.every(x => x.title && x.body), true, "every step has a title and a body");
eq(s.find(x => x.id === "search").keys.join("+"), "Super+Space", "search keys");
eq(s.find(x => x.id === "widgets").keys.join("+"), "Super+Alt+W", "widgets keys");
eq(s.find(x => x.id === "keys").keys.join("+"), "Super+/", "keys keys");
eq(w.next(6, 7), 7, "next on the last step is done");
eq(w.next(0, 7), 1, "next");
eq(w.next(7, 7), 7, "next stays done");
eq(w.prev(0), 0, "prev stops at the first");
eq(w.prev(3), 2, "prev");
eq(s.every(x => x.art && typeof x.hint === "string"), true, "every step names its art and has a hint");
eq(s.every(x => x.keys.length === 0 || x.hint.length > 0), true, "keys come with a hint");
eq(s.find(x => x.id === "centre").keys.join("+"), "Super+Alt+C", "centre keys");
eq(s.find(x => x.id === "settings").keys.join("+"), "Super+,", "settings keys");
eq(w.eyebrow(0, 7), "WELCOME TO VITRUM", "the first step greets");
eq(w.eyebrow(2, 7), "STEP 3 OF 7", "later steps say where you are");
eq(w.clampStep(9, 7), 6, "a jump past the end stops at the last");
eq(w.clampStep(-1, 7), 0, "a jump before the start stops at the first");
eq(w.clampStep(2.4, 7), 2, "a jump is a whole step");
eq(w.phase(0, 0, 1), 0, "phase starts at 0");
eq(w.phase(1, 0, 1), 1, "phase ends at 1");
eq(w.phase(0.2, 0.3, 0.5), 0, "phase waits for its delay");
eq(w.phase(0.9, 0.3, 0.5), 1, "phase holds at 1 after its span");
eq(w.phase(0.5, 0, 1) > 0.5, true, "phase eases out");
